#!/usr/bin/env node
// Collects every meta.json "discrepancies" entry into DISCREPANCIES.md.
//
// These are places where nodejs/node docs and actual behavior disagree, found
// while writing and testing the skills. Each is a candidate doc fix (or bug
// report) upstream. Entries are either strings or { doc, claim, behavior, example }.
//
// Usage: node tools/discrepancies.mjs [--stdout]

import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const lines = [
  '# Doc/behavior discrepancies',
  '',
  'Generated by `node tools/discrepancies.mjs` from each skill\'s `meta.json`. Each',
  'entry is a place where the nodejs/node docs at the skill\'s pinned commit and the',
  'observed behavior disagree. **Not yet triaged upstream.** Verify before filing.',
  '',
];
let total = 0;
for (const skill of (await readdir(join(ROOT, 'skills'))).sort()) {
  let meta;
  try {
    meta = JSON.parse(await readFile(join(ROOT, 'skills', skill, 'meta.json'), 'utf8'));
  } catch {
    continue;
  }
  const list = meta.discrepancies ?? [];
  if (list.length === 0) continue;
  total += list.length;
  lines.push(`## ${skill} (nodejs/node ${meta.nodejsCommit})`, '');
  for (const d of list) {
    if (typeof d === 'string') {
      lines.push(`- ${d}`);
    } else {
      lines.push(`- **${d.doc ?? 'docs'}**: ${d.claim ?? ''}`);
      if (d.behavior) lines.push(`  - Observed: ${d.behavior}`);
      if (d.example) lines.push(`  - Example: \`${d.example}\``);
    }
  }
  lines.push('');
}
lines.splice(6, 0, `${total} entries.`, '');
const text = `${lines.join('\n').trimEnd()}\n`;
if (process.argv.includes('--stdout')) process.stdout.write(text);
else {
  await writeFile(join(ROOT, 'DISCREPANCIES.md'), text);
  console.log(`wrote DISCREPANCIES.md (${total} entries)`);
}
